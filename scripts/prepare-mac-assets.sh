#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
FRONTEND_DIR="$PROJECT_ROOT/frontend"
BUILD_DIR="$FRONTEND_DIR/build"
source "$PROJECT_ROOT/scripts/branding-env.sh"

SOURCE_PNG="$PROJECT_ROOT/$BRANDING_APP_ICON_PNG"
LOGO_PNG="$PROJECT_ROOT/$BRANDING_LOGO_MARK_PNG"
TRAY_PNG="$PROJECT_ROOT/$BRANDING_TRAY_MARK_PNG"
ASSET_LOGO_PNG="$PROJECT_ROOT/$BRANDING_ASSET_LOGO_PNG"
ICON_PNG="$PROJECT_ROOT/$BRANDING_BUILD_ICON_PNG"
TRAY_TEMPLATE="$PROJECT_ROOT/$BRANDING_TRAY_TEMPLATE_PNG"
ICNS_PATH="$PROJECT_ROOT/$BRANDING_BUILD_ICON_ICNS"

mkdir -p "$BUILD_DIR"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT
export CLANG_MODULE_CACHE_PATH="$TMP_DIR/clang-module-cache"
export SWIFT_MODULECACHE_PATH="$TMP_DIR/swift-module-cache"

swift "$PROJECT_ROOT/scripts/write-mac-icon.swift" "$SOURCE_PNG" "$ICON_PNG" "$ICNS_PATH"
mkdir -p "$(dirname "$ASSET_LOGO_PNG")"
cp "$LOGO_PNG" "$ASSET_LOGO_PNG"
mkdir -p "$(dirname "$TRAY_TEMPLATE")"
cp "$TRAY_PNG" "$TRAY_TEMPLATE"
